import registry from "@/data/devices.json";
import virtualRegistry from "@/data/devices.virtual.json";
import { DeviceBinding, PhysicalCamera, PosTerminal, WearableBinding, type HubEvent, type LocationMessage, type NormalisedReading, type Origin, type PosOrderEvent, type SimulatorReport, type TelemetryMessage } from "./contracts";
import { SIMULATOR_ID, virtualKey } from "./fleet";

/**
 * In-process telemetry hub (server-side). Prototype stand-in for the production
 * pipeline (MQTT broker → Redis Streams/Kafka → TimescaleDB): it de-duplicates
 * messages, applies bindings + calibration, keeps a short replay buffer for
 * resumable SSE streams (device readings and POS order events share one
 * sequence), and tracks device last-seen times.
 *
 * Two registries are loaded: physical devices (src/data/devices.json) and the
 * simulated hardware fleet (src/data/devices.virtual.json, generated by
 * scripts/generate-fleet.ts). Every event is stamped with its `origin`
 * ("physical" | "virtual") from the registry — never from the message — so
 * simulated hardware can never be shown as LIVE.
 * Stored on globalThis so dev-server hot reloads don't drop state.
 */
interface DeviceStats {
  messages: number;
  duplicates: number;
  /** Buffered readings delivered late (device catching up after an outage). */
  late: number;
  rejected: Record<string, number>;
}

interface HubState {
  seq: number;
  buffer: HubEvent[];
  seen: Map<string, number>;
  lastSeen: Map<string, { at: number; battery?: number; rssi?: number; firmware?: string }>;
  stats: Map<string, DeviceStats>;
  terminals: Map<string, { at: number; orders: number; duplicates: number }>;
  simulator: { report: SimulatorReport; receivedAt: number } | null;
  listeners: Set<(e: HubEvent) => void>;
}

const g = globalThis as unknown as { __opsHub?: HubState };
const hub: HubState = (g.__opsHub ??= { seq: 0, buffer: [], seen: new Map(), lastSeen: new Map(), stats: new Map(), terminals: new Map(), simulator: null, listeners: new Set() });
// State created by an older version of this module (hot reload) may lack newer fields.
hub.stats ??= new Map();
hub.terminals ??= new Map();
hub.simulator ??= null;

const BUFFER = 2000;
const DEDUPE_TTL_MS = 24 * 3600 * 1000;

export const BINDINGS: DeviceBinding[] = [...registry.devices, ...virtualRegistry.devices].map((d) => DeviceBinding.parse(d));
export const CAMERAS: PhysicalCamera[] = [...(registry.cameras as unknown[]), ...virtualRegistry.cameras].map((c) => PhysicalCamera.parse(c));
export const POS_TERMINALS: PosTerminal[] = [...(((registry as { posTerminals?: unknown[] }).posTerminals ?? []) as unknown[]), ...virtualRegistry.posTerminals].map((t) => PosTerminal.parse(t));

export const WEARABLES: WearableBinding[] = [...(((registry as { wearables?: unknown[] }).wearables ?? []) as unknown[]), ...(((virtualRegistry as { wearables?: unknown[] }).wearables ?? []) as unknown[])].map((w) => WearableBinding.parse(w));

export function wearableFor(tagId: string) {
  return WEARABLES.find((w) => w.tagId === tagId);
}

/** Tag secret: virtual tags derive theirs from VIRTUAL_FLEET_SECRET; physical tags (or their RTLS gateway) use DEVICE_KEYS. */
export function tagSecret(tagId: string): string | null {
  const w = wearableFor(tagId);
  if (!w) return null;
  if (w.virtual) return virtualKey(tagId);
  try {
    const keys = JSON.parse(process.env.DEVICE_KEYS ?? "{}") as Record<string, string>;
    return typeof keys[tagId] === "string" && keys[tagId].length >= 16 ? keys[tagId] : null;
  } catch {
    return null;
  }
}

/** Site frame → floor plan, using the binding's calibration. */
export function toPlan(w: WearableBinding, x: number, y: number): [number, number] {
  const { offsetX, offsetZ, rotationDeg, scale } = w.transform;
  const r = (rotationDeg * Math.PI) / 180;
  const sx = x * scale;
  const sy = y * scale;
  return [Math.round((sx * Math.cos(r) - sy * Math.sin(r) + offsetX) * 1000) / 1000, Math.round((sx * Math.sin(r) + sy * Math.cos(r) + offsetZ) * 1000) / 1000];
}

export type LocationIngestResult = { status: "accepted"; seq: number } | { status: "duplicate" };

/** Calibrate, de-duplicate, buffer and broadcast one RTLS position fix. */
export function ingestLocation(msg: LocationMessage, now = Date.now()): LocationIngestResult {
  const w = wearableFor(msg.tagId)!;
  const key = `loc:${msg.tagId}:${msg.messageId}`;
  if (hub.seen.has(key)) return { status: "duplicate" };
  hub.seen.set(key, now);
  hub.lastSeen.set(msg.tagId, { at: now, battery: msg.battery_pct });
  const [x, z] = toPlan(w, msg.x, msg.y);
  const origin: Origin = w.virtual ? "virtual" : "physical";
  const e: HubEvent = { type: "location", seq: ++hub.seq, branchId: w.branchId, staffId: w.staffId, tagId: w.tagId, x, z, accuracy: msg.accuracy_m, technology: w.technology, ts: Date.parse(msg.ts), receivedAt: now, origin, source: origin === "virtual" ? "virtual" : "live" };
  hub.buffer.push(e);
  if (hub.buffer.length > BUFFER) hub.buffer.splice(0, hub.buffer.length - BUFFER);
  for (const l of hub.listeners) l(e);
  return { status: "accepted", seq: e.seq };
}

/** Badge health for Settings → Integrations (no positions: those only go to authorised consoles). */
export function wearableStatus(now = Date.now()) {
  return WEARABLES.map((w) => {
    const seen = hub.lastSeen.get(w.tagId);
    return { tagId: w.tagId, branchId: w.branchId, staffId: w.staffId, technology: w.technology, virtual: w.virtual, lastSeenAt: seen?.at ?? null, online: !!seen && now - seen.at < Math.max(10, w.expectedIntervalSec * 5) * 1000, battery: seen?.battery ?? null, model: w.model ?? null };
  });
}

export function bindingsFor(deviceId: string) {
  return BINDINGS.filter((b) => b.deviceId === deviceId);
}

export function isVirtualDevice(deviceId: string) {
  return BINDINGS.some((b) => b.deviceId === deviceId && b.virtual);
}

export function terminalFor(sourceId: string) {
  return POS_TERMINALS.find((t) => t.sourceId === sourceId);
}

/**
 * Device secret. Physical devices: DEVICE_KEYS='{"bench-coldroom-01":"<secret>"}' (production:
 * secrets manager / mTLS). Virtual devices: HMAC(VIRTUAL_FLEET_SECRET, deviceId) — a physical
 * key can never authenticate a virtual device id, nor the reverse.
 */
export function deviceSecret(deviceId: string): string | null {
  if (isVirtualDevice(deviceId)) return virtualKey(deviceId);
  try {
    const keys = JSON.parse(process.env.DEVICE_KEYS ?? "{}") as Record<string, string>;
    return typeof keys[deviceId] === "string" && keys[deviceId].length >= 16 ? keys[deviceId] : null;
  } catch {
    return null;
  }
}

/** Order-webhook secret for a sender: virtual terminals use their derived key, everything else POS_WEBHOOK_SECRET. */
export function posSecret(sourceId: string): string | null {
  if (terminalFor(sourceId)?.virtual) return virtualKey(sourceId);
  const s = process.env.POS_WEBHOOK_SECRET;
  return s && s.length >= 16 ? s : null;
}

/** Key the hardware simulator signs its status heartbeat with. */
export function simulatorSecret() {
  return virtualKey(SIMULATOR_ID);
}

const statsFor = (id: string) => {
  let s = hub.stats.get(id);
  if (!s) hub.stats.set(id, (s = { messages: 0, duplicates: 0, late: 0, rejected: {} }));
  return s;
};

/** Count a message refused at the edge (e.g. clock skew) against its device for fleet health. */
export function noteRejected(deviceId: string, reason: string) {
  if (!bindingsFor(deviceId).length) return;
  const s = statsFor(deviceId);
  s.rejected[reason] = (s.rejected[reason] ?? 0) + 1;
}

export type IngestResult = { status: "accepted"; readings: number } | { status: "duplicate" } | { status: "unbound"; metrics: string[] };

export function ingest(msg: TelemetryMessage, now = Date.now()): IngestResult {
  // Expire old de-duplication keys lazily.
  if (hub.seen.size > 50_000) for (const [k, t] of hub.seen) if (now - t > DEDUPE_TTL_MS) hub.seen.delete(k);
  const key = `${msg.deviceId}:${msg.messageId}`;
  const stats = statsFor(msg.deviceId);
  if (hub.seen.has(key)) {
    stats.duplicates++;
    return { status: "duplicate" };
  }
  hub.seen.set(key, now);
  stats.messages++;

  const ts = Date.parse(msg.ts);
  const bindings = bindingsFor(msg.deviceId);
  const origin: Origin = bindings.some((b) => b.virtual) ? "virtual" : "physical";
  // Battery / signal / firmware describe the device now; a buffered (older) message must not overwrite newer values.
  const prev = hub.lastSeen.get(msg.deviceId);
  const interval = bindings[0]?.expectedIntervalSec ?? 60;
  if (now - ts > interval * 2000) stats.late++;
  hub.lastSeen.set(msg.deviceId, prev && now - ts > interval * 2000 ? { ...prev, at: now } : { at: now, battery: msg.battery_pct, rssi: msg.rssi_dbm, firmware: msg.firmware });

  let accepted = 0;
  const unbound: string[] = [];
  for (const r of msg.readings) {
    const b = bindings.find((x) => x.metric === r.metric && (x.channel ?? null) === (r.channel ?? null));
    if (!b) {
      unbound.push(r.metric);
      continue;
    }
    const reading: NormalisedReading = {
      type: "reading",
      seq: ++hub.seq,
      branchId: b.branchId,
      equipmentId: b.equipmentId,
      sensorCode: b.sensorCode,
      deviceId: msg.deviceId,
      metric: r.metric,
      value: Math.round((r.value + b.calibrationOffset) * 100) / 100,
      ts,
      receivedAt: now,
      expectedIntervalSec: b.expectedIntervalSec,
      origin,
      source: origin === "virtual" ? "virtual" : "live",
    };
    hub.buffer.push(reading);
    accepted++;
    for (const l of hub.listeners) l(reading);
  }
  if (hub.buffer.length > BUFFER) hub.buffer.splice(0, hub.buffer.length - BUFFER);
  return accepted ? { status: "accepted", readings: accepted } : { status: "unbound", metrics: unbound };
}

export type OrderIngestResult = { status: "accepted"; seq: number } | { status: "duplicate" };

/** Buffer and broadcast a validated POS / ordering-system event (idempotent on its key). */
export function ingestOrder(sourceId: string, event: PosOrderEvent, now = Date.now()): OrderIngestResult {
  const key = `order:${sourceId}:${event.idempotencyKey}`;
  const t = hub.terminals.get(sourceId) ?? { at: now, orders: 0, duplicates: 0 };
  hub.terminals.set(sourceId, t);
  if (hub.seen.has(key)) {
    t.duplicates++;
    return { status: "duplicate" };
  }
  hub.seen.set(key, now);
  t.at = now;
  if (event.status === "RECEIVED") t.orders++;
  const origin: Origin = terminalFor(sourceId)?.virtual ? "virtual" : "physical";
  const e: HubEvent = { type: "order", seq: ++hub.seq, branchId: event.branchId, receivedAt: now, sourceId, event, origin, source: origin === "virtual" ? "virtual" : "live" };
  hub.buffer.push(e);
  if (hub.buffer.length > BUFFER) hub.buffer.splice(0, hub.buffer.length - BUFFER);
  for (const l of hub.listeners) l(e);
  return { status: "accepted", seq: e.seq };
}

/** A brand-new subscriber only gets readings this recent, so stale data never looks live. */
export const FRESH_REPLAY_MS = 5 * 60 * 1000;

/**
 * Readings to replay to a subscriber. Resuming (`afterSeq` > 0, from Last-Event-ID) replays
 * everything still buffered after that id; a fresh connection gets only recent readings.
 */
export function backlog(branchId: string | null, afterSeq: number, now = Date.now()) {
  const minReceived = afterSeq > 0 ? 0 : now - FRESH_REPLAY_MS;
  return hub.buffer.filter((r) => r.seq > afterSeq && r.receivedAt >= minReceived && (!branchId || r.branchId === branchId));
}

export function subscribe(fn: (e: HubEvent) => void) {
  hub.listeners.add(fn);
  return () => hub.listeners.delete(fn);
}

export function reportSimulator(report: SimulatorReport, now = Date.now()) {
  hub.simulator = { report, receivedAt: now };
}

/** Latest hardware-simulator heartbeat; `running` while heartbeats keep arriving. */
export function simulatorStatus(now = Date.now()) {
  if (!hub.simulator) return null;
  return { ...hub.simulator.report, receivedAt: hub.simulator.receivedAt, running: now - hub.simulator.receivedAt < 90_000 };
}

export function deviceStatus(now = Date.now()) {
  return BINDINGS.map((b) => {
    const seen = hub.lastSeen.get(b.deviceId);
    const st = hub.stats.get(b.deviceId);
    return {
      deviceId: b.deviceId,
      branchId: b.branchId,
      target: b.equipmentId ?? b.sensorCode ?? null,
      metric: b.metric,
      model: b.model ?? null,
      virtual: b.virtual,
      expectedIntervalSec: b.expectedIntervalSec,
      keyConfigured: deviceSecret(b.deviceId) !== null,
      lastSeenAt: seen?.at ?? null,
      online: !!seen && now - seen.at < b.expectedIntervalSec * 3 * 1000,
      battery: seen?.battery ?? null,
      rssi: seen?.rssi ?? null,
      firmware: seen?.firmware ?? null,
      messages: st?.messages ?? 0,
      duplicates: st?.duplicates ?? 0,
      late: st?.late ?? 0,
      rejected: Object.values(st?.rejected ?? {}).reduce((a, n) => a + n, 0),
    };
  });
}

export function terminalStatus() {
  return POS_TERMINALS.map((t) => {
    const s = hub.terminals.get(t.sourceId);
    return { sourceId: t.sourceId, branchId: t.branchId, name: t.name, model: t.model ?? null, virtual: t.virtual, keyConfigured: posSecret(t.sourceId) !== null, lastSeenAt: s?.at ?? null, orders: s?.orders ?? 0, duplicates: s?.duplicates ?? 0 };
  });
}

/** Test helper: reset hub state. */
export function __resetHub() {
  hub.seq = 0;
  hub.buffer = [];
  hub.seen.clear();
  hub.lastSeen.clear();
  hub.stats.clear();
  hub.terminals.clear();
  hub.simulator = null;
  hub.listeners.clear();
}
