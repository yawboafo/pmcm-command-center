import { z } from "zod";

/**
 * Canonical integration contracts (v1).
 *
 * Every external system — temperature probes, equipment controllers, camera
 * gateways, POS / Chris B order webhooks — is translated into these messages at
 * the edge. The rest of the platform (safety rules, alerts, 3D twin, analytics)
 * only ever sees these shapes, so swapping a simulated source for a real one
 * never touches UI or business logic.
 *
 * Wire format: JSON over HTTPS (signed, see ./signing.ts) or MQTT
 * (topic `pmcm/v1/{branchCode}/{deviceId}/telemetry`, same payload).
 */

export const DataSourceKind = z.enum(["live", "simulated"]);
export type DataSourceKind = z.infer<typeof DataSourceKind>;

/** Physical quantities a device may report. Units are fixed per metric. */
export const Metric = z.enum([
  "temperature_c", // air temperature in a fridge/freezer/hot-holding cabinet
  "probe_temperature_c", // food core temperature (cook verification)
  "oil_quality_pct", // fryer oil total-polar-material derived quality, 100 = fresh
  "door_open", // 1 = open, 0 = closed
  "power_w", // equipment power draw
  "humidity_pct",
  "status", // 1 = OK, 0 = fault (equipment controllers)
]);
export type Metric = z.infer<typeof Metric>;

export const Reading = z.object({
  metric: Metric,
  value: z.number().finite(),
  /** Optional channel on multi-probe devices. */
  channel: z.string().max(32).optional(),
});

export const TelemetryMessage = z.object({
  v: z.literal(1),
  /** Unique per message (UUID); used for de-duplication of retries. */
  messageId: z.string().min(8).max(64),
  deviceId: z
    .string()
    .min(3)
    .max(64)
    .regex(/^[a-zA-Z0-9._:-]+$/),
  /** Device clock (must be NTP-synchronised). */
  ts: z.iso.datetime({ offset: true }),
  readings: z.array(Reading).min(1).max(32),
  battery_pct: z.number().min(0).max(100).optional(),
  rssi_dbm: z.number().min(-140).max(0).optional(),
  firmware: z.string().max(32).optional(),
});
export type TelemetryMessage = z.infer<typeof TelemetryMessage>;

/** A device bound to a place in a branch floor plan. */
export const DeviceBinding = z
  .object({
    deviceId: z.string(),
    branchId: z.string(),
    /**
     * Preferred: the floor-plan equipment the device is installed on (e.g. "walk-in-cold-1").
     * Equipment ids are stable across editor changes; sensor ids are regenerated by auto-placement.
     */
    equipmentId: z.string().optional(),
    /** Alternative for sensors not attached to equipment (e.g. a QC probe): floor-plan Sensor.code, e.g. "SNS-031". */
    sensorCode: z.string().optional(),
    metric: Metric,
    channel: z.string().optional(),
    /** Added to raw values (from the latest calibration certificate). */
    calibrationOffset: z.number().default(0),
    /** Expected reporting interval; the device is flagged offline after 3× this. */
    expectedIntervalSec: z.number().int().min(5).max(3600).default(60),
    model: z.string().optional(),
    installedAt: z.string().optional(),
    lastCalibratedAt: z.string().optional(),
  })
  .refine((b) => b.equipmentId || b.sensorCode, {
    message: "Binding needs equipmentId or sensorCode",
  });
export type DeviceBinding = z.infer<typeof DeviceBinding>;

/** Normalised reading after binding + calibration — what the platform consumes. */
export interface NormalisedReading {
  /** Monotonic sequence (SSE event id) for resumable streams. */
  seq: number;
  branchId: string;
  equipmentId?: string;
  sensorCode?: string;
  deviceId: string;
  metric: Metric;
  value: number;
  /** Device timestamp (epoch ms). */
  ts: number;
  receivedAt: number;
  expectedIntervalSec: number;
  source: "live";
}

/**
 * Physical camera — only usable when explicitly authorised for the branch.
 * Streams are served by a media gateway (e.g. MediaMTX: RTSP in → WebRTC/WHEP or HLS out);
 * browsers never receive RTSP URLs or camera credentials.
 */
export const PhysicalCamera = z.object({
  cameraId: z.string(),
  branchId: z.string(),
  name: z.string(),
  /** Virtual camera in the floor plan that matches this camera's pose (for side-by-side viewing). */
  virtualCameraId: z.string().optional(),
  protocol: z.enum(["webrtc-whep", "hls"]),
  /** Gateway-relative path; the server combines it with CAMERA_GATEWAY_URL. */
  streamPath: z.string(),
  authorisation: z.object({
    approvedBy: z.string(),
    approvedAt: z.string(),
    purpose: z.string(),
    privacyNoticeUrl: z.string().url(),
    retentionDays: z.number().int().min(0).max(365),
  }),
  enabled: z.boolean(),
});
export type PhysicalCamera = z.infer<typeof PhysicalCamera>;

/** Order lifecycle event from POS / Chris B / partner webhooks. */
export const PosOrderEvent = z.object({
  v: z.literal(1),
  idempotencyKey: z.string().min(8).max(128),
  branchId: z.string(),
  externalRef: z.string(),
  channel: z.enum([
    "walk-in",
    "online",
    "chris-b-app",
    "phone",
    "delivery-partner",
    "pos",
  ]),
  fulfilment: z.enum(["pickup", "dine-in", "delivery"]),
  status: z.enum([
    "RECEIVED",
    "ACCEPTED",
    "READY",
    "COMPLETED",
    "CANCELLED",
    "REFUNDED",
  ]),
  lines: z
    .array(
      z.object({
        menuId: z.string(),
        qty: z.number().int().min(1).max(99),
        unitPriceGhs: z.number().min(0),
      }),
    )
    .max(50),
  ts: z.iso.datetime({ offset: true }),
});
export type PosOrderEvent = z.infer<typeof PosOrderEvent>;
