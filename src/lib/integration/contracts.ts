import { z } from "zod";

/**
 * Canonical integration contracts (v1).
 *
 * Every external system — temperature probes, equipment controllers, camera
 * gateways, POS / Chris B order webhooks — is translated into these messages at
 * the edge. The rest of the platform (safety rules, alerts, 3D twin, analytics)
 * only ever sees these shapes, so swapping a simulated source for a real one
 * never touches UI or business logic.
 *
 * Wire format: JSON over HTTPS (signed, see ./signing.ts) or MQTT
 * (topic `ops/v1/{branchCode}/{deviceId}/telemetry`, same payload).
 */

/**
 * Provenance of a value: "live" = physical device/system, "simulated" = in-browser simulation,
 * "virtual" = simulated hardware sending through the real pipeline (shown as SIM DEVICE, never LIVE).
 */
export const DataSourceKind = z.enum(["live", "simulated", "virtual"]);
export type DataSourceKind = z.infer<typeof DataSourceKind>;

/** Where a pipeline event physically came from, decided server-side from the registry — never from the message. */
export type Origin = "physical" | "virtual";

/** Physical quantities a device may report. Units are fixed per metric. */
export const Metric = z.enum([
  "temperature_c", // air temperature in a fridge/freezer/hot-holding cabinet
  "probe_temperature_c", // food core temperature (cook verification)
  "oil_quality_pct", // fryer oil total-polar-material derived quality, 100 = fresh
  "door_open", // 1 = open, 0 = closed
  "power_w", // equipment power draw
  "humidity_pct",
  "status", // 1 = OK, 0 = fault (equipment controllers)
]);
export type Metric = z.infer<typeof Metric>;

export const Reading = z.object({
  metric: Metric,
  value: z.number().finite(),
  /** Optional channel on multi-probe devices. */
  channel: z.string().max(32).optional(),
});

export const TelemetryMessage = z.object({
  v: z.literal(1),
  /** Unique per message (UUID); used for de-duplication of retries. */
  messageId: z.string().min(8).max(64),
  deviceId: z
    .string()
    .min(3)
    .max(64)
    .regex(/^[a-zA-Z0-9._:-]+$/),
  /** Device clock (must be NTP-synchronised). */
  ts: z.iso.datetime({ offset: true }),
  readings: z.array(Reading).min(1).max(32),
  battery_pct: z.number().min(0).max(100).optional(),
  rssi_dbm: z.number().min(-140).max(0).optional(),
  firmware: z.string().max(32).optional(),
});
export type TelemetryMessage = z.infer<typeof TelemetryMessage>;

/** A device bound to a place in a branch floor plan. */
export const DeviceBinding = z
  .object({
    deviceId: z.string(),
    branchId: z.string(),
    /**
     * Preferred: the floor-plan equipment the device is installed on (e.g. "walk-in-cold-1").
     * Equipment ids are stable across editor changes; sensor ids are regenerated by auto-placement.
     */
    equipmentId: z.string().optional(),
    /** Alternative for sensors not attached to equipment (e.g. a QC probe): floor-plan Sensor.code, e.g. "SNS-031". */
    sensorCode: z.string().optional(),
    metric: Metric,
    channel: z.string().optional(),
    /** Added to raw values (from the latest calibration certificate). */
    calibrationOffset: z.number().default(0),
    /** Expected reporting interval; the device is flagged offline after 3× this. */
    expectedIntervalSec: z.number().int().min(5).max(3600).default(60),
    model: z.string().optional(),
    installedAt: z.string().optional(),
    lastCalibratedAt: z.string().optional(),
    /** Simulated hardware (scripts/hardware-sim.ts). Its key is derived from VIRTUAL_FLEET_SECRET; its data shows as SIM DEVICE. */
    virtual: z.boolean().default(false),
  })
  .refine((b) => b.equipmentId || b.sensorCode, {
    message: "Binding needs equipmentId or sensorCode",
  });
export type DeviceBinding = z.infer<typeof DeviceBinding>;

/** Normalised reading after binding + calibration — what the platform consumes. */
export interface NormalisedReading {
  type: "reading";
  /** Monotonic sequence (SSE event id) for resumable streams. */
  seq: number;
  branchId: string;
  equipmentId?: string;
  sensorCode?: string;
  deviceId: string;
  metric: Metric;
  value: number;
  /** Device timestamp (epoch ms). */
  ts: number;
  receivedAt: number;
  expectedIntervalSec: number;
  /** Physical device or simulated hardware (from the registry's `virtual` flag). */
  origin: Origin;
  /** Provenance shown in the UI: LIVE for physical devices, SIM DEVICE for virtual ones. */
  source: "live" | "virtual";
}

/**
 * Physical camera — only usable when explicitly authorised for the branch.
 * Streams are served by a media gateway (e.g. MediaMTX: RTSP in → WebRTC/WHEP or HLS out);
 * browsers never receive RTSP URLs or camera credentials.
 */
export const PhysicalCamera = z.object({
  cameraId: z.string(),
  branchId: z.string(),
  name: z.string(),
  /** Virtual camera in the floor plan that matches this camera's pose (for side-by-side viewing). */
  virtualCameraId: z.string().optional(),
  /** `mjpeg` is served by the simulated camera gateway (scripts/camera-sim.ts) and proxied by /api/cameras/{id}/mjpeg. */
  protocol: z.enum(["webrtc-whep", "hls", "mjpeg"]),
  /** Gateway-relative path; the server combines it with CAMERA_GATEWAY_URL. */
  streamPath: z.string(),
  /** Required for real cameras; simulated cameras film nobody (synthetic test pattern). */
  authorisation: z
    .object({
      approvedBy: z.string(),
      approvedAt: z.string(),
      purpose: z.string(),
      privacyNoticeUrl: z.string().url(),
      retentionDays: z.number().int().min(0).max(365),
    })
    .optional(),
  enabled: z.boolean(),
  /** Simulated camera (synthetic video from the camera simulator); shown as SIM CAMERA, never LIVE. */
  virtual: z.boolean().default(false),
}).refine((c) => c.virtual || c.authorisation, { message: "Physical cameras need a recorded authorisation" });
export type PhysicalCamera = z.infer<typeof PhysicalCamera>;

/**
 * A registered order source (POS terminal, ordering app backend). Unregistered sources still sign
 * with POS_WEBHOOK_SECRET and count as physical; virtual terminals sign with a key derived from
 * VIRTUAL_FLEET_SECRET and their orders show as SIM DEVICE.
 */
export const PosTerminal = z.object({
  sourceId: z.string().regex(/^[a-zA-Z0-9._:-]{2,64}$/),
  branchId: z.string(),
  name: z.string(),
  model: z.string().optional(),
  /** Floor-plan equipment the terminal stands on (e.g. "pos-counter-1"), if any. */
  equipmentId: z.string().optional(),
  virtual: z.boolean().default(false),
});
export type PosTerminal = z.infer<typeof PosTerminal>;

/** Order lifecycle event from POS / Chris B / partner webhooks. */
export const PosOrderEvent = z.object({
  v: z.literal(1),
  idempotencyKey: z.string().min(8).max(128),
  branchId: z.string(),
  externalRef: z.string(),
  channel: z.enum([
    "walk-in",
    "online",
    "chris-b-app",
    "phone",
    "delivery-partner",
    "pos",
  ]),
  fulfilment: z.enum(["pickup", "dine-in", "delivery"]),
  status: z.enum([
    "RECEIVED",
    "ACCEPTED",
    "READY",
    "COMPLETED",
    "CANCELLED",
    "REFUNDED",
  ]),
  lines: z
    .array(
      z.object({
        menuId: z.string(),
        qty: z.number().int().min(1).max(99),
        unitPriceGhs: z.number().min(0),
      }),
    )
    .max(50),
  ts: z.iso.datetime({ offset: true }),
});
export type PosOrderEvent = z.infer<typeof PosOrderEvent>;

/** A validated, de-duplicated order event as streamed to the command center. */
export interface NormalisedOrderEvent {
  type: "order";
  seq: number;
  branchId: string;
  receivedAt: number;
  /** Webhook source id (x-ops-source), e.g. "chris-b". */
  sourceId: string;
  event: PosOrderEvent;
  /** Physical POS / ordering system, or a virtual terminal (from the terminal registry). */
  origin: Origin;
  source: "live" | "virtual";
}

/**
 * Heartbeat from the hardware simulator (scripts/hardware-sim.ts) describing what it is
 * simulating, so Settings → Integrations can show the injected faults. Signed with the key
 * derived from VIRTUAL_FLEET_SECRET for the id "hardware-sim".
 */
export const SimulatorReport = z.object({
  v: z.literal(1),
  startedAt: z.iso.datetime({ offset: true }),
  speed: z.number().min(0.1).max(1000),
  branches: z.array(z.string()).max(100),
  devices: z.number().int().min(0),
  terminals: z.number().int().min(0),
  faults: z
    .array(z.object({ deviceId: z.string().max(64), kind: z.string().max(32), since: z.iso.datetime({ offset: true }), injected: z.boolean() }))
    .max(500),
  offline: z.array(z.string().max(64)).max(2000),
});
export type SimulatorReport = z.infer<typeof SimulatorReport>;

/** Everything the hub streams, in one sequence so a single Last-Event-ID resumes both. */
export type HubEvent = NormalisedReading | NormalisedOrderEvent | NormalisedLocation;

/**
 * Staff wearable (UWB or BLE badge) read by an RTLS (real-time location system). The RTLS
 * reports positions in its own site frame; the binding carries the calibration transform to
 * the branch floor plan: plan = rotate(rotationDeg) · (site · scale) + offset.
 * Staff location is personal data: every binding records the notice the wearer acknowledged.
 */
export const WearableBinding = z.object({
  tagId: z.string().regex(/^[a-zA-Z0-9._:-]{3,64}$/),
  branchId: z.string(),
  /** Simulation staff id ("staff-3") — production: the HR / rota employee id. */
  staffId: z.string(),
  technology: z.enum(["uwb", "ble"]),
  transform: z.object({ offsetX: z.number().default(0), offsetZ: z.number().default(0), rotationDeg: z.number().default(0), scale: z.number().positive().default(1) }).default({ offsetX: 0, offsetZ: 0, rotationDeg: 0, scale: 1 }),
  expectedIntervalSec: z.number().min(0.2).max(60).default(1),
  model: z.string().optional(),
  consent: z.object({ noticeVersion: z.string(), acknowledgedAt: z.string() }),
  virtual: z.boolean().default(false),
});
export type WearableBinding = z.infer<typeof WearableBinding>;

/** One position fix from the RTLS for a tag (site frame, metres). */
export const LocationMessage = z.object({
  v: z.literal(1),
  messageId: z.string().min(8).max(64),
  tagId: z.string().regex(/^[a-zA-Z0-9._:-]{3,64}$/),
  ts: z.iso.datetime({ offset: true }),
  x: z.number().finite(),
  /** Site-frame horizontal axis that maps to the floor plan's z. */
  y: z.number().finite(),
  /** Estimated horizontal error (1σ), metres. */
  accuracy_m: z.number().min(0).max(50),
  battery_pct: z.number().min(0).max(100).optional(),
  /** Anchors that contributed to this fix. */
  anchors: z.number().int().min(0).max(64).optional(),
});
export type LocationMessage = z.infer<typeof LocationMessage>;

/** A calibrated staff position, as streamed to the command center. */
export interface NormalisedLocation {
  type: "location";
  seq: number;
  branchId: string;
  staffId: string;
  tagId: string;
  /** Floor-plan coordinates (metres). */
  x: number;
  z: number;
  accuracy: number;
  technology: "uwb" | "ble";
  ts: number;
  receivedAt: number;
  origin: Origin;
  source: "live" | "virtual";
}
