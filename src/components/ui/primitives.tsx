"use client";

import type { ReactNode } from "react";
import { UI_POLICY } from "@/config/platform";

export function cx(...c: Array<string | false | null | undefined>) {
  return c.filter(Boolean).join(" ");
}

/** Status palette (hex, because MapLibre paint and three.js materials cannot read CSS variables). Mirrors --ok / --watch / --act in globals.css. */
export const STATUS_COLOR = {
  normal: "#3ccf8e",
  ok: "#3ccf8e",
  warning: "#f5b02e",
  attention: "#f5b02e",
  critical: "#f0483e",
  closed: "#6b7280",
  offline: "#6b7280",
} as const;

export function StatusDot({ status, pulse }: { status: keyof typeof STATUS_COLOR; pulse?: boolean }) {
  return (
    <span className="relative inline-flex h-2.5 w-2.5 shrink-0">
      {pulse && <span className="absolute inline-flex h-full w-full animate-ping rounded-full opacity-60" style={{ background: STATUS_COLOR[status] }} />}
      <span className="relative inline-flex h-2.5 w-2.5 rounded-full" style={{ background: STATUS_COLOR[status] }} />
    </span>
  );
}

/** Marks data that comes from the simulation, never from live operations. Hidden unless UI_POLICY.showSimulatedLabels. */
export function SimBadge({ className, label = "SIMULATED" }: { className?: string; label?: string }) {
  if (!UI_POLICY.showSimulatedLabels) return null;
  return (
    <span title="Generated by the demo simulation — not real operational data" className={cx("inline-flex items-center gap-1 rounded border border-amber-400/30 bg-amber-400/10 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-amber-300", className)}>
      ◆ {label}
    </span>
  );
}

/** Live data from a connected, authenticated device or system. */
export function LiveBadge({ className, label = "LIVE" }: { className?: string; label?: string }) {
  return (
    <span title="Real reading from a connected device" className={cx("inline-flex items-center gap-1 rounded border border-emerald-400/40 bg-emerald-400/15 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-emerald-300", className)}>
      <span className="h-1.5 w-1.5 animate-pulse rounded-full bg-emerald-400" /> {label}
    </span>
  );
}

/** Simulated hardware sending through the real integration pipeline — exercised end to end, but not a real device. */
export function SimDeviceBadge({ className, label = "SIM DEVICE" }: { className?: string; label?: string }) {
  if (!UI_POLICY.showSimulatedLabels) return null;
  return (
    <span title="From simulated hardware through the real integration pipeline — not a physical device" className={cx("inline-flex items-center gap-1 rounded border border-fuchsia-400/40 bg-fuchsia-400/10 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-fuchsia-300", className)}>
      ◈ {label}
    </span>
  );
}

/** Provenance badge: LIVE for physical device data, SIM DEVICE for simulated hardware, SIMULATED otherwise. */
export function SourceBadge({ source, className }: { source: "live" | "simulated" | "virtual"; className?: string }) {
  if (source === "live") return <LiveBadge className={className} />;
  if (source === "virtual") return <SimDeviceBadge className={className} />;
  return <SimBadge className={className} />;
}

/**
 * Data provenance used across the command center:
 * LIVE — from a connected physical source · SIM DEVICE — simulated hardware through the
 * real pipeline · SIMULATED — generated by the simulation ·
 * ESTIMATED — calculated from available data · UNAVAILABLE — no reliable source exists.
 */
export type Provenance = "live" | "virtual" | "simulated" | "estimated" | "unavailable";

/** Calculated from available information (e.g. a predicted ready time), not observed. */
export function EstimatedBadge({ className, label = "ESTIMATED" }: { className?: string; label?: string }) {
  return (
    <span title="Calculated from available data — not an observed value" className={cx("inline-flex items-center gap-1 rounded border border-violet-400/35 bg-violet-400/10 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-violet-300", className)}>
      ≈ {label}
    </span>
  );
}

/** No reliable source exists for this value. */
export function UnavailableBadge({ className, label = "UNAVAILABLE" }: { className?: string; label?: string }) {
  return (
    <span title="No connected or verified source for this value" className={cx("inline-flex items-center gap-1 rounded border border-white/15 bg-white/5 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-white/45", className)}>
      ∅ {label}
    </span>
  );
}

export function ProvenanceBadge({ p, className }: { p: Provenance; className?: string }) {
  if (p === "live") return <LiveBadge className={className} />;
  if (p === "virtual") return <SimDeviceBadge className={className} />;
  if (p === "estimated") return <EstimatedBadge className={className} />;
  if (p === "unavailable") return <UnavailableBadge className={className} />;
  return <SimBadge className={className} />;
}

export function VerifiedBadge({ className, label = "VERIFIED" }: { className?: string; label?: string }) {
  return <span className={cx("inline-flex items-center gap-1 rounded border border-emerald-400/30 bg-emerald-400/10 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-emerald-300", className)}>✓ {label}</span>;
}

export function ConceptBadge({ className, label = "CONCEPTUAL" }: { className?: string; label?: string }) {
  return <span className={cx("inline-flex items-center gap-1 rounded border border-sky-400/30 bg-sky-400/10 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-sky-300", className)}>◇ {label}</span>;
}

