"use client";

import type { ReactNode } from "react";

export function cx(...c: Array<string | false | null | undefined>) {
  return c.filter(Boolean).join(" ");
}

export const STATUS_COLOR = {
  normal: "#22c55e",
  ok: "#22c55e",
  warning: "#eab308",
  attention: "#eab308",
  critical: "#ef4444",
  closed: "#6b7280",
  offline: "#6b7280",
} as const;

export function StatusDot({ status, pulse }: { status: keyof typeof STATUS_COLOR; pulse?: boolean }) {
  return (
    <span className="relative inline-flex h-2.5 w-2.5 shrink-0">
      {pulse && <span className="absolute inline-flex h-full w-full animate-ping rounded-full opacity-60" style={{ background: STATUS_COLOR[status] }} />}
      <span className="relative inline-flex h-2.5 w-2.5 rounded-full" style={{ background: STATUS_COLOR[status] }} />
    </span>
  );
}

/** Marks data that comes from the simulation, never from live operations. */
export function SimBadge({ className, label = "SIMULATED" }: { className?: string; label?: string }) {
  return (
    <span title="Generated by the demo simulation — not real operational data" className={cx("inline-flex items-center gap-1 rounded border border-amber-400/30 bg-amber-400/10 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-amber-300", className)}>
      ◆ {label}
    </span>
  );
}

/** Live data from a connected, authenticated device or system. */
export function LiveBadge({ className, label = "LIVE" }: { className?: string; label?: string }) {
  return (
    <span title="Real reading from a connected device" className={cx("inline-flex items-center gap-1 rounded border border-emerald-400/40 bg-emerald-400/15 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-emerald-300", className)}>
      <span className="h-1.5 w-1.5 animate-pulse rounded-full bg-emerald-400" /> {label}
    </span>
  );
}

/** Provenance badge: LIVE for device data, SIMULATED otherwise. */
export function SourceBadge({ source, className }: { source: "live" | "simulated"; className?: string }) {
  return source === "live" ? <LiveBadge className={className} /> : <SimBadge className={className} />;
}

export function VerifiedBadge({ className, label = "VERIFIED" }: { className?: string; label?: string }) {
  return <span className={cx("inline-flex items-center gap-1 rounded border border-emerald-400/30 bg-emerald-400/10 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-emerald-300", className)}>✓ {label}</span>;
}

export function ConceptBadge({ className, label = "CONCEPTUAL" }: { className?: string; label?: string }) {
  return <span className={cx("inline-flex items-center gap-1 rounded border border-sky-400/30 bg-sky-400/10 px-1.5 py-px font-mono text-[9px] font-semibold tracking-wider text-sky-300", className)}>◇ {label}</span>;
}

export function Glass({ children, className }: { children: ReactNode; className?: string }) {
  return <div className={cx("glass rounded-xl", className)}>{children}</div>;
}

export function Stat({ label, value, sub, tone }: { label: string; value: ReactNode; sub?: ReactNode; tone?: "red" | "green" | "yellow" | "default" }) {
  const color = tone === "red" ? "text-red-400" : tone === "green" ? "text-emerald-400" : tone === "yellow" ? "text-amber-300" : "text-white";
  return (
    <div className="min-w-0">
      <div className="truncate text-[10px] font-medium uppercase tracking-wider text-white/45">{label}</div>
      <div className={cx("font-display text-lg font-semibold tabular-nums leading-tight", color)}>{value}</div>
      {sub && <div className="truncate text-[10px] text-white/40">{sub}</div>}
    </div>
  );
}

export function Btn({ children, onClick, active, tone, className, disabled, title, size = "sm" }: { children: ReactNode; onClick?: () => void; active?: boolean; tone?: "red" | "default" | "ghost"; className?: string; disabled?: boolean; title?: string; size?: "xs" | "sm" }) {
  return (
    <button
      type="button"
      title={title}
      disabled={disabled}
      onClick={onClick}
      className={cx(
        "inline-flex items-center justify-center gap-1.5 rounded-lg border font-medium transition disabled:cursor-not-allowed disabled:opacity-40",
        size === "xs" ? "px-2 py-1 text-[11px]" : "px-3 py-1.5 text-xs",
        tone === "red" ? "border-brand-red/60 bg-brand-red text-white hover:bg-brand-red/85" : active ? "border-white/25 bg-white/15 text-white" : tone === "ghost" ? "border-transparent text-white/70 hover:bg-white/10 hover:text-white" : "border-white/10 bg-white/5 text-white/80 hover:bg-white/10 hover:text-white",
        className,
      )}
    >
      {children}
    </button>
  );
}

export function SectionTitle({ children, right }: { children: ReactNode; right?: ReactNode }) {
  return (
    <div className="mb-2 flex items-center justify-between gap-2">
      <h3 className="font-display text-[11px] font-semibold uppercase tracking-[0.14em] text-white/55">{children}</h3>
      {right}
    </div>
  );
}

export function Empty({ children }: { children: ReactNode }) {
  return <div className="rounded-lg border border-dashed border-white/10 p-4 text-center text-xs text-white/40">{children}</div>;
}

export function Meter({ value, color = "#EE1D25" }: { value: number; color?: string }) {
  return (
    <div className="h-1.5 w-full overflow-hidden rounded-full bg-white/10">
      <div className="h-full rounded-full transition-all" style={{ width: `${Math.max(0, Math.min(1, value)) * 100}%`, background: color }} />
    </div>
  );
}
